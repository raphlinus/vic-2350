"""Convert a 16x16 tileset PNG into symbolasm statics for vic's renderer.

Usage: tools/tiles.py ~/Downloads/dandelion_tileset.png > tiles.sy

Tiles are 4 bits per pixel, the left pixel of each pair in the low
nibble, 8 bytes per row, 128 bytes per tile. Each tile uses one of a
few 16 color palettes, where index 0 is transparent and shows the
background color. Each palette is expanded to the 1 KB fast form: for
every byte, two RGB565 pixels in one word, the left in the low half.

The screen map covers 640x480 with the tileset repeated, each entry a
pointer to the tile's data and a pointer to its fast palette. Empty
tiles point at an all-zero tile.
"""

import struct
import sys
import zlib

TILE = 16
SCREEN_W, SCREEN_H = 640 // TILE, 480 // TILE
BACKGROUND = (0x40, 0x30, 0x50)


def read_png_rgba(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat = 8, b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos : pos + 8])
        body = data[pos + 8 : pos + 8 + length]
        if kind == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert (depth, color, interlace) == (8, 6, 0), "need 8 bit RGBA, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    raw = zlib.decompress(idat)
    stride = w * 4
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pred) & 255
        rows.append([tuple(line[x * 4 : x * 4 + 4]) for x in range(w)])
        prev = line
    return w, h, rows


def rgb565(c):
    r, g, b = c[:3]
    return (b >> 3) | ((g & 0xFC) << 3) | ((r & 0xF8) << 8)


def main():
    w, h, px = read_png_rgba(sys.argv[1])
    tw, th = w // TILE, h // TILE
    # Each tile's pixels as colors, None for transparent
    tiles = []
    for ty in range(th):
        for tx in range(tw):
            t = [
                [
                    px[ty * TILE + y][tx * TILE + x][:3]
                    if px[ty * TILE + y][tx * TILE + x][3] >= 128
                    else None
                    for x in range(TILE)
                ]
                for y in range(TILE)
            ]
            tiles.append(t)
    colors = [{c for row in t for c in row if c is not None} for t in tiles]
    nonempty = [i for i, cs in enumerate(colors) if cs]
    # Greedy palette packing, biggest color sets first: 15 colors each
    # plus transparent.
    palettes, assign = [], {}
    for i in sorted(nonempty, key=lambda i: -len(colors[i])):
        assert len(colors[i]) <= 15, f"tile {i} has {len(colors[i])} colors"
        for p, pal in enumerate(palettes):
            if len(pal | colors[i]) <= 15:
                pal |= colors[i]
                assign[i] = p
                break
        else:
            palettes.append(set(colors[i]))
            assign[i] = len(palettes) - 1
    palettes = [sorted(p) for p in palettes]

    out = sys.stdout
    out.write("// Generated by tools/tiles.py from %s; don't edit.\n" % sys.argv[1].split("/")[-1])
    out.write(f"// {len(nonempty)} tiles, {len(palettes)} palettes.\n\n")
    out.write(f"const TILE_BYTES = 128\nconst MAP_W = {SCREEN_W}\nconst MAP_H = {SCREEN_H}\n\n")

    # Tile 0 is empty; the rest in tileset order.
    index = {}
    words = [0] * 32
    for i in nonempty:
        index[i] = len(index) + 1
        pal = palettes[assign[i]]
        for y in range(TILE):
            row = [0 if c is None else pal.index(c) + 1 for c in tiles[i][y]]
            for x in range(0, TILE, 8):
                word = 0
                for k in range(8):
                    word |= row[x + k] << (4 * k)
                words.append(word)
    out.write(f"// 4bpp tiles, tile 0 empty\n#[link_section = \".data\"]\nstatic tiles: [u32; {len(words)}] = [\n")
    for i in range(0, len(words), 8):
        out.write("    " + ", ".join(f"0x{v:08x}" for v in words[i : i + 8]) + ",\n")
    out.write("]\n\n")

    bg = rgb565(BACKGROUND)
    fast = []
    for pal in palettes:
        cols = [bg] + [rgb565(c) for c in pal] + [bg] * (15 - len(pal))
        fast += [cols[b & 15] | (cols[b >> 4] << 16) for b in range(256)]
    out.write(f"// 1 KB fast palettes: byte to two RGB565 pixels, left in the low half\n#[link_section = \".data\"]\nstatic palettes: [u32; {len(fast)}] = [\n")
    for i in range(0, len(fast), 8):
        out.write("    " + ", ".join(f"0x{v:08x}" for v in fast[i : i + 8]) + ",\n")
    out.write("]\n\n")

    out.write("// The screen, the tileset repeated: tile data, fast palette\n")
    out.write(f"#[link_section = \".data\"]\nstatic tile_map: [*u32; {2 * SCREEN_W * SCREEN_H}] = [\n")
    for sy in range(SCREEN_H):
        entries = []
        for sx in range(SCREEN_W):
            i = (sy % th) * tw + (sx % tw)
            t = index.get(i, 0)
            p = assign.get(i, 0)
            entries.append(f"&tiles + {t * 128}, &palettes + {p * 1024}")
        out.write("    " + ", ".join(entries) + ",\n")
    out.write("]\n")


main()
