# Convert pioasm's JSON output into symbolasm: one static array holding
# all the programs back to back, for loading at instruction 0, with JMP
# targets relocated, and constants for each program's offset, wrap and
# public labels (absolute, as EXECCTRL and INSTR_MEM want them).
#
# Usage: pioasm -o json sd.pio | python3 tools/pio2sy.py NAME > sd_pio.sy

import json
import sys

name = sys.argv[1]
progs = json.load(sys.stdin)["programs"]
words = []
out = ["// Generated by tools/pio2sy.py from pioasm output; don't edit.\n"]
for p in progs:
    offset = len(words)
    for ins in p["instructions"]:
        w = int(ins["hex"], 16)
        # JMP is opcode 0; its target is the low 5 bits
        if w >> 13 == 0:
            w = (w & ~0x1F) | ((w & 0x1F) + offset)
        words.append(w)
    prefix = p["name"].upper()
    out.append(f"const {prefix}_OFFSET = {offset}\n")
    out.append(f"const {prefix}_WRAP_TARGET = {offset + p['wrapTarget']}\n")
    out.append(f"const {prefix}_WRAP = {offset + p['wrap']}\n")
    for label, addr in p["publicLabels"].items():
        out.append(f"const {prefix}_{label.upper()} = {offset + addr}\n")
if len(words) > 32:
    sys.exit(f"pio2sy: {len(words)} instructions don't fit in 32")
out.append(f"static {name}: [u32; {len(words)}] = [\n")
for i in range(0, len(words), 8):
    row = ", ".join(f"0x{w:04x}" for w in words[i : i + 8])
    out.append(f"    {row},\n")
out.append("]\n")
sys.stdout.write("".join(out))
